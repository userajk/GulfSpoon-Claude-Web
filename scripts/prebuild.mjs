// Runs before `next dev` and `next build` (npm predev/prebuild hooks).
// 1. Writes src/content/generated/image-manifest.json (every file under public/images).
// 2. Writes src/content/generated/scheduled-content.ts, importing every file in
//    src/content/<collection>/recipes/*.ts and src/content/<collection>/guides/*.ts.
// 3. Prints the publishing schedule: live, scheduled, and held back for a missing hero image.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const contentDir = path.join(root, "src", "content");
const outDir = path.join(contentDir, "generated");
fs.mkdirSync(outDir, { recursive: true });

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

// 1. Image manifest
const publicDir = path.join(root, "public");
const images = walk(path.join(publicDir, "images"))
  .map((p) => "/" + path.relative(publicDir, p).split(path.sep).join("/"))
  .sort();
fs.writeFileSync(path.join(outDir, "image-manifest.json"), JSON.stringify(images, null, 2) + "\n");

// 2. Content index
const collections = fs
  .readdirSync(contentDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name !== "generated")
  .map((e) => e.name)
  .sort();

const recipeFiles = [];
const guideFiles = [];
for (const c of collections) {
  for (const [sub, list] of [["recipes", recipeFiles], ["guides", guideFiles]]) {
    const dir = path.join(contentDir, c, sub);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".ts")).sort()) {
      list.push(`${c}/${sub}/${f.replace(/\.ts$/, "")}`);
    }
  }
}

const ident = (p) => "c_" + p.replace(/[^a-zA-Z0-9]/g, "_");
const lines = [
  "// AUTO-GENERATED by scripts/prebuild.mjs. Do not edit.",
  'import type { Recipe } from "@/lib/schema/recipe";',
  'import type { Story } from "@/lib/schema/story";',
  ...recipeFiles.map((p) => `import { recipe as ${ident(p)} } from "@/content/${p}";`),
  ...guideFiles.map((p) => `import { story as ${ident(p)} } from "@/content/${p}";`),
  "",
  `export const scheduledRecipes: Recipe[] = [${recipeFiles.map(ident).join(", ")}];`,
  `export const scheduledStories: Story[] = [${guideFiles.map(ident).join(", ")}];`,
  "",
];
fs.writeFileSync(path.join(outDir, "scheduled-content.ts"), lines.join("\n"));

// 3. Schedule report
const today = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Dubai" }).format(new Date());
const imageSet = new Set(images);
const rows = [...recipeFiles, ...guideFiles].map((p) => {
  const src = fs.readFileSync(path.join(contentDir, p + ".ts"), "utf8");
  const slug = src.match(/slug:\s*"([^"]+)"/)?.[1] ?? p;
  const date = src.match(/publishedAt:\s*"([^"]+)"/)?.[1] ?? "????-??-??";
  const hero = src.match(/heroImage:\s*"([^"]+)"/)?.[1] ?? "";
  const status = !imageSet.has(hero)
    ? date <= today ? "HELD (missing image)" : "scheduled, image missing"
    : date <= today ? "live" : "scheduled";
  return { date, kind: p.includes("/guides/") ? "guide" : "recipe", slug, status, hero };
});
rows.sort((a, b) => a.date.localeCompare(b.date) || a.kind.localeCompare(b.kind));
console.log(`\nScheduled content (today in Dubai: ${today})`);
for (const r of rows) console.log(`  ${r.date}  ${r.kind.padEnd(6)}  ${r.status.padEnd(25)}  ${r.slug}`);
const missing = rows.filter((r) => r.status.includes("image"));
if (missing.length) {
  console.log(`\n  ${missing.length} item(s) need a hero image before they can go live:`);
  for (const r of missing) console.log(`    public${r.hero}`);
}
console.log("");
